 const c=await client();await c.request('admin/login','POST',{username:'admin',password:'Cricket@2026'});
 const p=c.state.products[1];
 let edit={id:p.id,stock:10,price:10000,regularPrice:10000,previousStock:p.stock,previousPrice:p.price,note:'Discount test',onSale:true,discountType:'percent',discountValue:20};
 assert.equal((await c.request('admin/inventory','PATCH',edit)).status,200);
 let fresh=(await c.request('store')).data.products.find(x=>x.id===p.id);
