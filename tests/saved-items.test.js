test('favorites require login, persist per customer, reject CSRF, and remove idempotently',async()=>{
 const a=await client(),b=await client(),id=a.state.products[0].id;
 assert.equal((await a.request('account/saved-items')).status,401);
 assert.equal((await a.request('account/saved-items','PUT',{productId:id})).status,401);
 assert.equal((await a.request('account/register','POST',profile('a@example.com'))).status,200);
 assert.equal((await b.request('account/register','POST',profile('b@example.com'))).status,200);
 assert.equal((await a.request('account/saved-items','PUT',{productId:id},'wrong')).status,403);
 assert.equal((await a.request('account/saved-items','PUT',{productId:'missing'})).status,404);
 assert.deepEqual((await a.request('account/saved-items','PUT',{productId:id})).data.savedItems,[id]);
 assert.deepEqual((await a.request('account/saved-items','PUT',{productId:id})).data.savedItems,[id]);
 assert.deepEqual((await b.request('account/saved-items')).data.savedItems,[]);
 assert.deepEqual((await a.request('store')).data.user.savedItems,[id]);
 const disk=JSON.parse(readFileSync(join(process.env.DATA_DIR,'store.json'),'utf8'));
 assert.deepEqual(disk.users.find(u=>u.email==='a@example.com').savedItems,[id]);
 await a.request('account/logout','POST',{});
 assert.equal((await a.request('account/saved-items')).status,401);
 assert.equal((await a.request('store')).data.user,null);
 const fresh=await client();const login=await fresh.request('account/login','POST',profile('a@example.com'));
 assert.deepEqual(login.data.user.savedItems,[id]);
 assert.deepEqual((await fresh.request('account/saved-items','DELETE',{productId:id})).data.savedItems,[]);
 assert.deepEqual((await fresh.request('account/saved-items','DELETE',{productId:id})).data.savedItems,[]);
});
